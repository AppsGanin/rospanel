var updateRef = flag.Bool("update-theme-ref", false, "rewrite docs/plugins/theme-data.md")

const themeRefPath = "../../docs/plugins/theme-data.md"

// The theme authors' reference of the page's data is generated from the page's
// own types and their comments, so it cannot drift: this test fails when it is
// stale (go test ./internal/sub -run ThemeDataReference -update-theme-ref).
func TestThemeDataReference(t *testing.T) {
	got := themeDataReference(t)
	if *updateRef {
		if err := os.WriteFile(themeRefPath, []byte(got), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(themeRefPath)
	if err != nil || string(want) != got {
		t.Fatalf("%s is stale: go test ./internal/sub -run ThemeDataReference -update-theme-ref", themeRefPath)
	}
}

func themeDataReference(t *testing.T) string {
	docs := fieldDocs(t)
	var b strings.Builder
	b.WriteString(`<!-- Generated by TestThemeDataReference (internal/sub/theme_ref_test.go): do not edit. -->
# Subscription page data for theme templates

What ` + "`theme/<section>.html`" + ` sees as ` + "`.`" + ` at the top of a section (and as ` + "`$`" + `
anywhere in it). Lists (` + "`[]…`" + `) are what ` + "`range`" + ` may go over; inside, ` + "`.`" + ` is one
element. Texts in the reader's language are in ` + "`.L`" + `.

`)
	seen := map[reflect.Type]bool{}
	var walk func(t reflect.Type, prefix string, depth int)
	walk = func(t reflect.Type, prefix string, depth int) {
		for t.Kind() == reflect.Pointer || t.Kind() == reflect.Slice || t.Kind() == reflect.Map {
			t = t.Elem()
		}
		if t.Kind() != reflect.Struct || seen[t] || t.PkgPath() != reflect.TypeOf(pageData{}).PkgPath() {
			return
		}
		seen[t] = true
		defer delete(seen, t)
		indent := strings.Repeat("  ", depth)
		for _, f := range reflect.VisibleFields(t) {
			if !f.IsExported() || f.Anonymous || len(f.Index) > 1 && !embeddedVisible(t, f) {
				continue
			}
			if t == reflect.TypeOf(Access{}) && (f.Name == "Markup" || f.Name == "NoPanelStyles" || f.Name == "ThemeCSS") {
				continue // how the panel wires the theme in, not page data
			}
			if t == reflect.TypeOf(pageData{}) && f.Name == "L" {
				fmt.Fprintf(&b, "%s- `%s%s` — the page's texts in the reader's language: %s\n", indent, prefix, f.Name, textKeys(f.Type))
				continue
			}
			owner := t
			if len(f.Index) > 1 {
				owner = t.FieldByIndex(f.Index[:len(f.Index)-1]).Type
			}
			doc := docs[owner.Name()+"."+f.Name]
			fmt.Fprintf(&b, "%s- `%s%s` %s%s\n", indent, prefix, f.Name, "`"+typeLabel(f.Type)+"`", dash(doc))
			walk(f.Type, ".", depth+1)
		}
		pt := reflect.PointerTo(t)
		for i := 0; i < pt.NumMethod(); i++ {
			m := pt.Method(i)
			var args []string
			for j := 1; j < m.Type.NumIn(); j++ {
				args = append(args, typeLabel(m.Type.In(j)))
			}
			sig := ""
			if len(args) > 0 {
				sig = " " + strings.Join(args, " ")
			}
			fmt.Fprintf(&b, "%s- `%s%s%s` `%s`%s\n", indent, prefix, m.Name, sig, typeLabel(m.Type.Out(0)), dash(docs[t.Name()+"."+m.Name]))
		}
	}
	walk(reflect.TypeOf(pageData{}), ".", 0)
	return b.String()
}

// embeddedVisible keeps the promoted fields of an embedded struct (the colours).
func embeddedVisible(_ reflect.Type, f reflect.StructField) bool { return f.IsExported() }

func dash(doc string) string {
	if doc == "" {
		return ""
	}
	return " — " + doc
}

func typeLabel(t reflect.Type) string {
	switch t.Kind() {
	case reflect.Pointer:
		return typeLabel(t.Elem()) + " (may be nil: use with)"
	case reflect.Slice:
		return "[]" + typeLabel(t.Elem())
	case reflect.Map:
		return "map[" + typeLabel(t.Key()) + "]" + typeLabel(t.Elem())
	}
	return typeName(t)
}

func textKeys(t reflect.Type) string {
	var names []string
	for _, f := range reflect.VisibleFields(t) {
		if f.IsExported() && !f.Anonymous {
			names = append(names, "`.L."+f.Name+"`")
		}
	}
	sort.Strings(names)
	return strings.Join(names, ", ")
}

// fieldDocs maps "Type.Field" (and "Type.Method") to its comment, one line.
func fieldDocs(t *testing.T) map[string]string {
	fset := token.NewFileSet()
	names, err := filepath.Glob("*.go")
	if err != nil {
		t.Fatal(err)
	}
	var files []*ast.File
	for _, name := range names {
		if strings.HasSuffix(name, "_test.go") {
			continue
		}
		f, err := parser.ParseFile(fset, name, nil, parser.ParseComments)
		if err != nil {
			t.Fatal(err)
		}
		files = append(files, f)
	}
	out := map[string]string{}
	clean := func(cg ...*ast.CommentGroup) string {
		for _, c := range cg {
			if c != nil {
				return strings.Join(strings.Fields(c.Text()), " ")
			}
		}
		return ""
	}
	{
		for _, f := range files {
			ast.Inspect(f, func(n ast.Node) bool {
				switch n := n.(type) {
				case *ast.TypeSpec:
					st, ok := n.Type.(*ast.StructType)
					if !ok {
						return true
					}
					for _, fl := range st.Fields.List {
						for _, name := range fl.Names {
							out[n.Name.Name+"."+name.Name] = clean(fl.Doc, fl.Comment)
						}
					}
				case *ast.FuncDecl:
					if n.Recv != nil && len(n.Recv.List) == 1 {
						rt := n.Recv.List[0].Type
						if s, ok := rt.(*ast.StarExpr); ok {
							rt = s.X
						}
						if id, ok := rt.(*ast.Ident); ok {
							out[id.Name+"."+n.Name.Name] = clean(n.Doc)
						}
					}
				}
				return true
			})
		}
	}
	return out
}
