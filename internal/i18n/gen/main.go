// Command gen regenerates the error catalogs the Go side answers with — English for
// the external API, Chinese and Arabic for the bots and the subscription page — from
// the panel's own dictionaries.
//
// The texts are NOT re-authored here: web/src/i18n/*.ts already hold a string for
// every err.* code (TestErrorCodesHaveDictionaryEntries makes sure of it), and a
// second hand-written copy would be a second thing to forget. This lifts them into Go
// so a server with no checkout beside it can still answer in those languages.
//
// Run with `go generate ./internal/i18n/...`; TestErrorCatalogIsCurrent fails when
// the generated file and the dictionaries have drifted apart.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strconv"

	"github.com/AppsGanin/rospanel/internal/i18n/dictcheck"
)

// catalogs pairs each generated Go variable with the dictionary it is lifted from.
var catalogs = []struct{ name, file string }{
	{"errEN", "en.ts"},
	{"errZH", "zh.ts"},
	{"errAR", "ar.ts"},
	{"errFA", "fa.ts"},
}

func main() {
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/i18n/gen. DO NOT EDIT.\n")
	b.WriteString("// Source: web/src/i18n/{en,zh,ar,fa}.ts (the `err` section).\n\n")
	b.WriteString("package i18n\n\n")
	b.WriteString("// errEN, errZH, errAR and errFA hold the text of every error code the panel can raise,\n")
	b.WriteString("// keyed by the same code the panel UI translates. The external API renders the\n")
	b.WriteString("// English one; the bots and the subscription page the reader's language. The panel\n")
	b.WriteString("// keeps translating in the browser, in whichever language the admin picked.\n")
	total := 0
	for _, c := range catalogs {
		entries, err := dictcheck.Errors(".", c.file)
		if err != nil {
			fmt.Fprintln(os.Stderr, "read dictionary:", err)
			os.Exit(1)
		}
		if len(entries) == 0 {
			fmt.Fprintf(os.Stderr, "no err.* entries in %s — did the dictionary shape change?\n", c.file)
			os.Exit(1)
		}
		keys := make([]string, 0, len(entries))
		for k := range entries {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		fmt.Fprintf(&b, "\nvar %s = map[string]string{\n", c.name)
		for _, k := range keys {
			fmt.Fprintf(&b, "\t%s: %s,\n", strconv.Quote(k), strconv.Quote(entries[k]))
		}
		b.WriteString("}\n")
		total += len(keys)
	}

	src, err := format.Source(b.Bytes())
	if err != nil {
		fmt.Fprintln(os.Stderr, "gofmt:", err)
		os.Exit(1)
	}
	if err := os.WriteFile("errcatalog_gen.go", src, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "write:", err)
		os.Exit(1)
	}
	fmt.Printf("errcatalog_gen.go: %d entries\n", total)
}
